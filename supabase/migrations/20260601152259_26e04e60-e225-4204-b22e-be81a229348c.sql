
-- 1. instructor_reports
CREATE TABLE public.instructor_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id BIGINT NOT NULL DEFAULT 1,
  batch_session_id BIGINT NOT NULL,
  batch_id BIGINT NOT NULL,
  studio_id BIGINT,
  instructor_id BIGINT NOT NULL,
  session_date DATE NOT NULL,
  style TEXT,
  students_present INTEGER NOT NULL DEFAULT 0,
  notes TEXT,
  -- Teaching & Conduct
  form BOOLEAN NOT NULL DEFAULT false,
  relationship_building BOOLEAN NOT NULL DEFAULT false,
  syllabus_followed BOOLEAN NOT NULL DEFAULT false,
  information_imparted BOOLEAN NOT NULL DEFAULT false,
  punctuality BOOLEAN NOT NULL DEFAULT false,
  -- Operations
  absentee_calls BOOLEAN NOT NULL DEFAULT false,
  absentee_update BOOLEAN NOT NULL DEFAULT false,
  attendance_marked BOOLEAN NOT NULL DEFAULT false,
  registration_followup BOOLEAN NOT NULL DEFAULT false,
  renewal_followup BOOLEAN NOT NULL DEFAULT false,
  -- Class Management
  playlist_prepared BOOLEAN NOT NULL DEFAULT false,
  videos_shot BOOLEAN NOT NULL DEFAULT false,
  story_posted BOOLEAN NOT NULL DEFAULT false,
  briefing_done BOOLEAN NOT NULL DEFAULT false,
  poa_shared BOOLEAN NOT NULL DEFAULT false,
  -- Ratings
  attire_rating SMALLINT NOT NULL DEFAULT 0 CHECK (attire_rating BETWEEN 0 AND 5),
  culture_rating SMALLINT NOT NULL DEFAULT 0 CHECK (culture_rating BETWEEN 0 AND 5),
  -- Generated scores
  total_score INTEGER GENERATED ALWAYS AS (
    (form::int + relationship_building::int + syllabus_followed::int + information_imparted::int + punctuality::int
     + absentee_calls::int + absentee_update::int + attendance_marked::int + registration_followup::int + renewal_followup::int
     + playlist_prepared::int + videos_shot::int + story_posted::int + briefing_done::int + poa_shared::int)
    + attire_rating + culture_rating
  ) STORED,
  compliance_pct NUMERIC(5,2) GENERATED ALWAYS AS (
    ROUND(
      ((form::int + relationship_building::int + syllabus_followed::int + information_imparted::int + punctuality::int
        + absentee_calls::int + absentee_update::int + attendance_marked::int + registration_followup::int + renewal_followup::int
        + playlist_prepared::int + videos_shot::int + story_posted::int + briefing_done::int + poa_shared::int)
       + attire_rating + culture_rating)::numeric * 100 / 25, 2)
  ) STORED,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (batch_session_id, instructor_id)
);

CREATE INDEX idx_instructor_reports_instructor_date ON public.instructor_reports (instructor_id, session_date DESC);
CREATE INDEX idx_instructor_reports_org_date ON public.instructor_reports (organization_id, session_date DESC);
CREATE INDEX idx_instructor_reports_studio ON public.instructor_reports (studio_id);
CREATE INDEX idx_instructor_reports_batch ON public.instructor_reports (batch_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.instructor_reports TO authenticated;
GRANT ALL ON public.instructor_reports TO service_role;

ALTER TABLE public.instructor_reports ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow authenticated read instructor_reports" ON public.instructor_reports FOR SELECT TO authenticated USING (true);
CREATE POLICY "Allow authenticated insert instructor_reports" ON public.instructor_reports FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "Allow authenticated update instructor_reports" ON public.instructor_reports FOR UPDATE TO authenticated USING (true);
CREATE POLICY "Allow authenticated delete instructor_reports" ON public.instructor_reports FOR DELETE TO authenticated USING (true);

-- 2. choreography_uploads
CREATE TABLE public.choreography_uploads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id BIGINT NOT NULL DEFAULT 1,
  report_id BIGINT NOT NULL REFERENCES public.instructor_reports(id) ON DELETE CASCADE,
  batch_id BIGINT,
  studio_id BIGINT,
  instructor_id BIGINT NOT NULL,
  style TEXT,
  taught_on DATE NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('choreography','practice','photo')),
  storage_path TEXT NOT NULL,
  mime_type TEXT,
  duration_sec INTEGER,
  thumbnail_path TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_choreo_uploads_instructor ON public.choreography_uploads (instructor_id, taught_on DESC);
CREATE INDEX idx_choreo_uploads_batch ON public.choreography_uploads (batch_id);
CREATE INDEX idx_choreo_uploads_style ON public.choreography_uploads (style);
CREATE INDEX idx_choreo_uploads_report ON public.choreography_uploads (report_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.choreography_uploads TO authenticated;
GRANT ALL ON public.choreography_uploads TO service_role;

ALTER TABLE public.choreography_uploads ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow authenticated read choreography_uploads" ON public.choreography_uploads FOR SELECT TO authenticated USING (true);
CREATE POLICY "Allow authenticated insert choreography_uploads" ON public.choreography_uploads FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "Allow authenticated update choreography_uploads" ON public.choreography_uploads FOR UPDATE TO authenticated USING (true);
CREATE POLICY "Allow authenticated delete choreography_uploads" ON public.choreography_uploads FOR DELETE TO authenticated USING (true);

-- 3. Storage bucket for class media
INSERT INTO storage.buckets (id, name, public)
VALUES ('class-media', 'class-media', true)
ON CONFLICT (id) DO NOTHING;

CREATE POLICY "Public read class-media" ON storage.objects FOR SELECT USING (bucket_id = 'class-media');
CREATE POLICY "Authenticated upload class-media" ON storage.objects FOR INSERT TO authenticated WITH CHECK (bucket_id = 'class-media');
CREATE POLICY "Authenticated update class-media" ON storage.objects FOR UPDATE TO authenticated USING (bucket_id = 'class-media');
CREATE POLICY "Authenticated delete class-media" ON storage.objects FOR DELETE TO authenticated USING (bucket_id = 'class-media');
