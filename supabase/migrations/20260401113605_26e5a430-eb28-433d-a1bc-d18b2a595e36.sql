
ALTER TABLE public.payments ADD COLUMN confirmed_by_staff_id bigint;

CREATE TABLE public.cash_payment_requests (
  id bigint generated by default as identity primary key,
  organization_id bigint NOT NULL DEFAULT 1,
  student_id bigint NOT NULL,
  staff_user_id bigint NOT NULL,
  token text NOT NULL UNIQUE DEFAULT gen_random_uuid()::text,
  amount numeric NOT NULL,
  gst numeric NOT NULL DEFAULT 0,
  final_amount numeric NOT NULL,
  enrollment_data jsonb NOT NULL,
  batch_ids jsonb NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  created_at timestamptz NOT NULL DEFAULT now(),
  confirmed_at timestamptz
);
ALTER TABLE public.cash_payment_requests ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow anon read cash_payment_requests" ON public.cash_payment_requests FOR SELECT TO anon USING (true);
CREATE POLICY "Allow anon update cash_payment_requests" ON public.cash_payment_requests FOR UPDATE TO anon USING (true);
CREATE POLICY "Allow anon insert cash_payment_requests" ON public.cash_payment_requests FOR INSERT TO anon WITH CHECK (true);
CREATE POLICY "Allow authenticated all cash_payment_requests" ON public.cash_payment_requests FOR ALL TO authenticated USING (true) WITH CHECK (true);
