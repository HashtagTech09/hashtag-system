
CREATE TABLE public.abandoned_carts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id bigint NOT NULL,
  organization_id bigint NOT NULL DEFAULT 1,
  batch_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
  cart_type text NOT NULL DEFAULT 'add',
  created_at timestamptz NOT NULL DEFAULT now(),
  reminded_at timestamptz,
  status text NOT NULL DEFAULT 'active'
);

ALTER TABLE public.abandoned_carts ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow anon insert abandoned_carts" ON public.abandoned_carts FOR INSERT TO anon WITH CHECK (true);
CREATE POLICY "Allow anon read abandoned_carts" ON public.abandoned_carts FOR SELECT TO anon USING (true);
CREATE POLICY "Allow anon update abandoned_carts" ON public.abandoned_carts FOR UPDATE TO anon USING (true);
CREATE POLICY "Allow authenticated all abandoned_carts" ON public.abandoned_carts FOR ALL TO authenticated USING (true) WITH CHECK (true);
