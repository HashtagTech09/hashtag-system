-- Add is_active to enrollments
ALTER TABLE public.enrollments
  ADD COLUMN IF NOT EXISTS is_active boolean NOT NULL DEFAULT true;

-- Application cases table
CREATE TABLE IF NOT EXISTS public.application_cases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL DEFAULT 1,
  enrollment_id bigint NOT NULL,
  student_id bigint NOT NULL,
  batch_id bigint NOT NULL,
  requested_by_user_id bigint,
  requested_at timestamptz NOT NULL DEFAULT now(),
  reason text,
  status text NOT NULL DEFAULT 'pending',
  reviewed_by_user_id bigint,
  reviewed_at timestamptz,
  review_notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_app_cases_org_status
  ON public.application_cases (organization_id, status);
CREATE INDEX IF NOT EXISTS idx_app_cases_enrollment
  ON public.application_cases (enrollment_id);

ALTER TABLE public.application_cases ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow authenticated read application_cases"
  ON public.application_cases FOR SELECT TO authenticated USING (true);
CREATE POLICY "Allow authenticated insert application_cases"
  ON public.application_cases FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "Allow authenticated update application_cases"
  ON public.application_cases FOR UPDATE TO authenticated USING (true);
CREATE POLICY "Allow authenticated delete application_cases"
  ON public.application_cases FOR DELETE TO authenticated USING (true);

ALTER PUBLICATION supabase_realtime ADD TABLE public.application_cases;